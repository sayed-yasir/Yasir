const RTL = { fa: true, ps: true };
const root = document.documentElement;
const reduce = matchMedia('(prefers-reduced-motion: reduce)');
const menuBtn = document.getElementById('menu');
const nav = document.getElementById('nav');
const themeBtn = document.getElementById('theme');
let current = 'en';

function t(key) { return translations[current][key]; }

function splitWords(el) {
  const words = el.textContent.trim().split(/\s+/);
  el.textContent = '';
  words.forEach((w, i) => {
    const o = document.createElement('span'); o.className = 'w';
    const s = document.createElement('span'); s.textContent = w; s.style.setProperty('--i', i);
    o.append(s); el.append(o, ' ');
  });
}

function setMenu(open) {
  nav.classList.toggle('open', open);
  menuBtn.setAttribute('aria-expanded', String(open));
  menuBtn.setAttribute('aria-label', t(open ? 'menu_close' : 'menu_open'));
}

function applyTheme(th) {
  root.dataset.theme = th;
  themeBtn.setAttribute('aria-label', t(th === 'dark' ? 'theme_to_light' : 'theme_to_dark'));
}

function setLang(lang) {
  if (!translations[lang]) lang = 'en';
  current = lang;
  root.lang = lang;
  root.dir = RTL[lang] ? 'rtl' : 'ltr';
  document.title = t('meta_title');
  document.querySelector('meta[name="description"]').setAttribute('content', t('meta_desc'));
  document.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
  document.querySelectorAll('[data-split]').forEach(splitWords);
  document.querySelectorAll('[data-i18n-aria]').forEach(el => { el.setAttribute('aria-label', t(el.dataset.i18nAria)); });
  document.querySelectorAll('[data-i18n-alt]').forEach(el => { el.alt = t(el.dataset.i18nAlt); });
  document.querySelectorAll('[data-lang]').forEach(b => b.setAttribute('aria-pressed', String(b.dataset.lang === lang)));
  applyTheme(root.dataset.theme);
  setMenu(nav.classList.contains('open'));
  try { localStorage.setItem('lang', lang); } catch (e) {}
}

document.querySelectorAll('[data-lang]').forEach(b => b.addEventListener('click', () => setLang(b.dataset.lang)));
menuBtn.addEventListener('click', () => setMenu(!nav.classList.contains('open')));
nav.querySelectorAll('a').forEach(a => a.addEventListener('click', () => setMenu(false)));
document.addEventListener('keydown', e => { if (e.key === 'Escape') setMenu(false); });

themeBtn.addEventListener('click', () => {
  const next = root.dataset.theme === 'dark' ? 'light' : 'dark';
  try { localStorage.setItem('theme', next); } catch (e) {}
  if (document.startViewTransition && !reduce.matches) {
    const r = themeBtn.getBoundingClientRect();
    const x = r.left + r.width / 2, y = r.top + r.height / 2;
    const rad = Math.hypot(Math.max(x, innerWidth - x), Math.max(y, innerHeight - y));
    document.startViewTransition(() => applyTheme(next)).ready.then(() => {
      root.animate(
        { clipPath: [`circle(0 at ${x}px ${y}px)`, `circle(${rad}px at ${x}px ${y}px)`] },
        { duration: 750, easing: 'cubic-bezier(.65,0,.2,1)', pseudoElement: '::view-transition-new(root)' }
      );
    }).catch(() => {});
  } else {
    root.classList.add('theme-anim');
    applyTheme(next);
    setTimeout(() => root.classList.remove('theme-anim'), 500);
  }
});

matchMedia('(prefers-color-scheme: light)').addEventListener('change', e => {
  let saved = null;
  try { saved = localStorage.getItem('theme'); } catch (err) {}
  if (!saved) applyTheme(e.matches ? 'light' : 'dark');
});

let saved = 'en';
try { saved = localStorage.getItem('lang') || 'en'; } catch (e) {}
setLang(saved);

if (reduce.matches) document.querySelectorAll('animateMotion').forEach(n => n.remove());

document.addEventListener('pointermove', e => {
  root.style.setProperty('--px', e.clientX + 'px');
  root.style.setProperty('--py', e.clientY + 'px');
  const c = e.target.closest && e.target.closest('.card');
  if (c) {
    const r = c.getBoundingClientRect();
    c.style.setProperty('--mx', (e.clientX - r.left) + 'px');
    c.style.setProperty('--my', (e.clientY - r.top) + 'px');
  }
}, { passive: true });

const targets = document.querySelectorAll('.card, .about > div, .contact > *, .section > h2');
targets.forEach((el, i) => { el.style.transitionDelay = (i % 2) * 90 + 'ms'; });
if ('IntersectionObserver' in window) {
  const io = new IntersectionObserver(entries => entries.forEach(en => {
    if (en.isIntersecting) { en.target.classList.add('in'); io.unobserve(en.target); }
  }), { threshold: 0.08 });
  targets.forEach(el => io.observe(el));
} else {
  targets.forEach(el => el.classList.add('in'));
}
